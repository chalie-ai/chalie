"""REST endpoint for the tool-calls namespace — one tool call, addressed by its id.

Routes (generated by the Endpoint base):
    GET    /api/tool-calls/<id>   One call's full record, result included — the
                                  read an opened row makes on demand. The live frame
                                  and the history chips carry the same ``id``.

Every other route answers the uniform 405. The route is cookie-only, like the
thread reads it sits beside: it serves the human chat surface.
"""

from __future__ import annotations

from typing import ClassVar, cast

from flask.typing import ResponseReturnValue

from api.endpoint import DocumentedResponse, Endpoint
from api.response.tool_calls import ToolCallDetail
from exceptions import NotFoundError
from services.turn_serializer_service import get_service as _serializer


class ToolCallsEndpoint(Endpoint):
    """The tool-call resource: one call's params, result and lifecycle."""

    id_type: ClassVar[type[int] | type[str]] = int
    cookie_only_methods: ClassVar[frozenset[str]] = frozenset({"get"})

    response_dto = {
        "get": DocumentedResponse(ToolCallDetail),
    }

    def get(self, id: int | str) -> ResponseReturnValue:
        """One tool call's full record, ``result`` included; 404 for an unknown id.

        Args:
            id: The tool_calls row id the live frame and the chips carry.

        Returns:
            The ToolCallDetail for this call.
        """
        record = _serializer().tool_call(cast("int", id))
        if record is None:
            raise NotFoundError("Not found")
        return ToolCallDetail.model_validate(record).single()
