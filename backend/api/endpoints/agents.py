"""REST endpoint for the agents namespace — the subagents still running.

Routes (generated by the Endpoint base):
    GET    /api/agents/all   Every running agent, oldest first — the read a page
                             makes on load and on every reconnect; from then on
                             each ``agent_changed`` frame keeps it current.

Every other route answers the uniform 405. The route is cookie-only: it serves
the human chat surface.
"""

from __future__ import annotations

from typing import ClassVar

from flask.typing import ResponseReturnValue

from api.endpoint import DocumentedResponse, Endpoint
from api.response.agents import AgentResponse
from api.response.response import Response
from models.agent import Agent
from services.agent_service import AgentService


class AgentsEndpoint(Endpoint):
    """The agents resource: the running rows, each as its frame carries it."""

    cookie_only_methods: ClassVar[frozenset[str]] = frozenset({"get_all"})

    response_dto = {"get_all": DocumentedResponse(AgentResponse, listing=True)}

    def get_all(self, page: int = 1, limit: int = 20) -> ResponseReturnValue:
        """One page of the running agents, oldest first."""
        running = Agent.running()
        start = (page - 1) * limit
        dtos = [AgentResponse.model_validate(AgentService.view(agent)) for agent in running[start:start + limit]]
        return Response.listing(dtos, page=page, limit=limit, total=len(running))
